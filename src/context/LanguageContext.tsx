interface LanguageContextValue {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => Promise<void>;
  translate: (text: string) => string;
}

const LanguageContext = createContext<LanguageContextValue | undefined>(undefined);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>('en');
  const [localLoaded, setLocalLoaded] = useState(false);
  const { profile, isLoading: isProfileLoading, updatePreferences } = useLocalProfile();

  useEffect(() => {
    AsyncStorage.getItem(APP_LANGUAGE_KEY)
      .then((storedLanguage) => {
        if (APP_LANGUAGES.some((item) => item.code === storedLanguage)) {
          setLanguageState(storedLanguage as AppLanguage);
        }
      })
      .catch((error: unknown) => console.error('Failed to load app language:', error))
      .finally(() => setLocalLoaded(true));
  }, []);

  useEffect(() => {
    const savedLanguage = profile?.preferences.language;
    if (!localLoaded || isProfileLoading || !savedLanguage || !APP_LANGUAGES.some((item) => item.code === savedLanguage)) return;
    AsyncStorage.setItem(APP_LANGUAGE_KEY, savedLanguage)
      .then(() => setLanguageState(savedLanguage))
      .catch((error: unknown) => console.error('Failed to save local language preference:', error));
  }, [profile?.preferences.language, isProfileLoading, localLoaded]);

  const setLanguage = useCallback(async (nextLanguage: AppLanguage) => {
    await AsyncStorage.setItem(APP_LANGUAGE_KEY, nextLanguage);
    setLanguageState(nextLanguage);
    if (profile) await updatePreferences({ language: nextLanguage });
  }, [profile, updatePreferences]);

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage,
    translate: (text) => {
      if (language === 'en') return text;
      const leadingWhitespace = text.match(/^\s*/)?.[0] ?? '';
      const trailingWhitespace = text.match(/\s*$/)?.[0] ?? '';
      const trimmedText = text.trim();
      const translated = translations[language][trimmedText]
        ?? commonTranslations[language][trimmedText]
        ?? trimmedText;
      return `${leadingWhitespace}${translated}${trailingWhitespace}`;
    },
  }), [language, setLanguage]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage(): LanguageContextValue {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within a LanguageProvider');
  return context;
}

export function LocalizedText({ children, ...props }: TextProps) {
  const { translate } = useLanguage();
  const localizedChildren = Children.map(children, (child) => {
    if (typeof child === 'string') return translate(child);
    return child;
  });

  return <ThemedText {...props}>{localizedChildren}</ThemedText>;
}

export function LocalizedTextInput(props: TextInputProps) {
  const { translate } = useLanguage();
  return <ThemedTextInput
    {...props}
    placeholder={props.placeholder ? translate(props.placeholder) : undefined}
    accessibilityLabel={props.accessibilityLabel ? translate(props.accessibilityLabel) : undefined}
  />;
}
